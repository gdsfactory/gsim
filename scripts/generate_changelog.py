"""Generate the documentation changelog from published GitHub release notes."""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path
from typing import Any
from urllib.error import URLError
from urllib.request import Request, urlopen

DEFAULT_REPOSITORY = "gdsfactory/gsim"
DEFAULT_OUTPUT_PATH = Path(__file__).resolve().parents[1] / "docs" / "CHANGELOG.md"
RELEASES_PER_PAGE = 100


def fetch_releases(
    repository: str, *, token: str | None = None
) -> list[dict[str, Any]]:
    """Fetch every release, including older pages, without changing GitHub state."""
    headers = {
        "Accept": "application/vnd.github+json",
        "User-Agent": "gsim-docs",
        "X-GitHub-Api-Version": "2022-11-28",
    }
    if token:
        headers["Authorization"] = f"Bearer {token}"

    releases = []
    page_number = 1
    while True:
        url = (
            f"https://api.github.com/repos/{repository}/releases"
            f"?per_page={RELEASES_PER_PAGE}&page={page_number}"
        )
        request = Request(url, headers=headers)  # noqa: S310
        with urlopen(request, timeout=30) as response:  # noqa: S310
            page = json.load(response)
        if not isinstance(page, list) or any(
            not isinstance(item, dict) for item in page
        ):
            raise ValueError("GitHub returned an invalid release list")
        releases.extend(page)
        if len(page) < RELEASES_PER_PAGE:
            return releases
        page_number += 1


def _normalize_notes(markdown: str) -> str:
    """Normalize heading depth and repeated PR bullets, preserving fenced code."""
    lines = []
    heading_depths = {}
    seen_pr_entries = set()
    fence_character = ""
    fence_length = 0
    for line in markdown.splitlines():
        fence = re.match(r"^\s{0,3}(`{3,}|~{3,})", line)
        if fence:
            marker = fence.group(1)
            if not fence_character:
                fence_character = marker[0]
                fence_length = len(marker)
            elif marker[0] == fence_character and len(marker) >= fence_length:
                fence_character = ""
        elif not fence_character:
            if re.match(
                r"^[-*] .+\[#\d+\]\(https://github\.com/[^)]+/pull/\d+\)", line
            ):
                if line in seen_pr_entries:
                    continue
                seen_pr_entries.add(line)
            heading = re.match(r"^#{1,6}(?=\s)", line)
            if heading:
                heading_depths[len(lines)] = len(heading[0])
        lines.append(line)
    if heading_depths:
        shallowest_heading = min(heading_depths.values())
        for line_index, depth in heading_depths.items():
            normalized_depth = min(depth - shallowest_heading + 3, 6)
            lines[line_index] = "#" * normalized_depth + lines[line_index][depth:]
    return "\n".join(lines)


def render_changelog(releases: list[dict[str, Any]], *, repository: str) -> str:
    """Render published versions and their original notes, newest publication first."""
    published_releases = [
        release
        for release in releases
        if not release.get("draft") and release.get("published_at")
    ]
    if not published_releases:
        raise ValueError("No published GitHub releases were found")
    published_releases.sort(key=lambda release: release["published_at"], reverse=True)

    sections = [
        "# Changelog",
        "<!-- Generated by scripts/generate_changelog.py from published releases; do not edit. -->",
        f"Release history from [GitHub Releases](https://github.com/{repository}/releases).",
    ]
    for release in published_releases:
        tag = release["tag_name"]
        date = release["published_at"].split("T", 1)[0]
        release_url = release["html_url"]
        prerelease_label = " (prerelease)" if release.get("prerelease") else ""
        sections.extend(
            [
                f"## {tag}{prerelease_label}",
                f"Released {date}. [View release]({release_url}).",
            ]
        )
        notes = (release.get("body") or "").strip()
        sections.append(
            _normalize_notes(notes)
            if notes
            else "No release notes were published for this version."
        )
    return "\n\n".join(sections) + "\n"


def main() -> int:
    """Fetch releases and replace the generated page only after successful rendering."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", default=DEFAULT_REPOSITORY)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT_PATH)
    arguments = parser.parse_args()
    token = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
    try:
        releases = fetch_releases(arguments.repository, token=token)
        changelog = render_changelog(releases, repository=arguments.repository)
    except (URLError, TimeoutError, ValueError) as error:
        if arguments.output.is_file() and arguments.output.stat().st_size:
            print(
                f"Warning: Cannot refresh changelog: {error}. "
                f"Using existing snapshot {arguments.output}",
                file=sys.stderr,
            )
            return 0
        raise SystemExit(f"Cannot generate changelog: {error}") from error
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    arguments.output.write_text(changelog, encoding="utf-8")
    print(f"Generated {arguments.output} from published GitHub releases")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
